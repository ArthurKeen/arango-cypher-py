"""Fetch, verify and cache LDBC SNB data sets (docs/ldbc_benchmark_plan.md D6).

Nothing generated by LDBC is committed. A data set is obtained on first use
into ``$LDBC_CACHE_DIR`` (default ``~/.cache/arango-cypher/ldbc``) and verified
against a pinned **content digest** before anything reads it. The SF0.003
samples are downloaded; scales LDBC publishes in no loadable form (SF0.1) are
generated with LDBC's own data generator (tests/ldbc/datagen.py, decision 12).

Why a content digest and not the archive's SHA-256: LDBC rebuilds the sample
archives (the SF0.003 zips fetched on 2026-10-23 were packed 2026-10-18), and
Spark names each part file with a fresh UUID, so the archive bytes change on
every republish while the rows do not. The digest covers each entity's
decompressed rows, sorted, keyed by entity path — independent of part-file
names, partitioning and zip metadata. If the *rows* change, the digest fails
and every recorded oracle snapshot is suspect, which is exactly when the run
must stop.
"""

from __future__ import annotations

import gzip
import hashlib
import logging
import os
import shutil
import tempfile
import urllib.request
import zipfile
from collections.abc import Callable, Iterator
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

logger = logging.getLogger(__name__)

Encoding = Literal["epoch_ms", "iso"]

#: Seconds a single download may take before it is abandoned.
DOWNLOAD_TIMEOUT_S = 120

#: Where the BI ``composite-projected-fk`` layout sits, in an archive or a Datagen output.
LAYOUT_SUBDIR = Path("graphs") / "csv" / "bi" / "composite-projected-fk"


class LdbcDatasetError(RuntimeError):
    """A data set could not be fetched, unpacked or verified."""


@dataclass(frozen=True)
class LdbcDataset:
    name: str
    scale_factor: str
    #: How ``datetime``/``date`` columns are written: epoch milliseconds (the
    #: Interactive v2 reference) or ISO-8601 text (the BI reference).
    encoding: Encoding
    #: Where the archive is downloaded from; ``None`` for a data set generated with Datagen.
    url: str | None
    #: Top-level directory inside the archive; ``""`` for a generated data set.
    archive_root: str
    #: :func:`content_digest` of ``initial_snapshot/``.
    content_digest: str
    #: ``ldbc_snb_datagen_spark`` commit named in the archive's README, or used to generate it.
    datagen_commit: str

    @property
    def generated(self) -> bool:
        return self.url is None

    @property
    def layout_dir_name(self) -> Path:
        return Path(self.archive_root) / LAYOUT_SUBDIR


