def cache_dir() -> Path:
    raw = os.environ.get("LDBC_CACHE_DIR", "").strip()
    return Path(raw).expanduser() if raw else Path.home() / ".cache" / "arango-cypher" / "ldbc"


def entity_dirs(root: Path) -> Iterator[Path]:
    """Every ``<part>/<Entity>`` directory under *root*, in sorted order."""
    for part in sorted(p for p in root.iterdir() if p.is_dir()):
        yield from sorted(p for p in part.iterdir() if p.is_dir())


def part_files(entity_dir: Path) -> list[Path]:
    """The CSV part files of one entity, sorted; Spark markers are skipped."""
    files = sorted(
        p for p in entity_dir.iterdir() if p.name.startswith("part-") and p.suffix in {".gz", ".csv"}
    )
    return files


def _read_lines(path: Path) -> list[bytes]:
    opener = gzip.open if path.suffix == ".gz" else open
    with opener(path, "rb") as fh:  # type: ignore[operator]
        return fh.read().splitlines()


def content_digest(snapshot_dir: Path) -> str:
    """SHA-256 over each entity's path and its sorted decompressed rows."""
    if not snapshot_dir.is_dir():
        raise LdbcDatasetError(f"cannot digest {snapshot_dir}: not a directory")
    h = hashlib.sha256()
    for ent in entity_dirs(snapshot_dir):
        h.update(f"{ent.parent.name}/{ent.name}\n".encode())
        rows: list[bytes] = []
        for f in part_files(ent):
            rows.extend(_read_lines(f))
        for row in sorted(rows):
            h.update(row + b"\n")
    return h.hexdigest()


#: ldbcouncil.org answers 403 to urllib's default ``Python-urllib/x.y`` agent.
_USER_AGENT = "arango-cypher-ldbc-harness/1.0 (+https://github.com/arango-solutions-org/arango-cypher)"


def _download(url: str, dest: Path) -> None:
    req = urllib.request.Request(url, headers={"User-Agent": _USER_AGENT})
    with urllib.request.urlopen(req, timeout=DOWNLOAD_TIMEOUT_S) as resp, dest.open("wb") as out:  # noqa: S310 — https URL from the pinned catalog
        shutil.copyfileobj(resp, out)


def _safe_extract(archive: Path, target: Path) -> None:
    """Extract *archive* into *target*, refusing members that escape it."""
    target_resolved = target.resolve()
    with zipfile.ZipFile(archive) as zf:
        for member in zf.infolist():
            dest = (target / member.filename).resolve()
            if dest != target_resolved and target_resolved not in dest.parents:
                raise LdbcDatasetError(
                    f"{archive.name}: member {member.filename!r} would extract outside {target}"
                )
        zf.extractall(target)


def _generate(ds: LdbcDataset, out: Path) -> None:
    from tests.ldbc.datagen import generate

    generate(ds.scale_factor, ds.encoding, out)


def _download_into(
    ds: LdbcDataset, url: str, tmp: Path, root: Path, downloader: Callable[[str, Path], None]
) -> None:
    archive = tmp / "archive.zip"
    logger.info("downloading LDBC data set %s from %s", ds.name, url)
    try:
        downloader(url, archive)
    except OSError as e:
        raise LdbcDatasetError(f"download of {ds.name} from {url} failed: {e}") from e
    try:
        _safe_extract(archive, root)
    except zipfile.BadZipFile as e:
        raise LdbcDatasetError(f"{ds.name}: downloaded archive is not a zip file: {e}") from e


def _generate_into(
    ds: LdbcDataset, tmp: Path, root: Path, generator: Callable[[LdbcDataset, Path], None]
) -> None:
    out = tmp / "datagen"
    logger.info("generating LDBC data set %s with Datagen %s (minutes, once)", ds.name, ds.datagen_commit[:8])
    generator(ds, out)
    top = LAYOUT_SUBDIR.parts[0]
    if not (out / top).is_dir():
        raise LdbcDatasetError(f"{ds.name}: Datagen output has no {top}/ directory under {out}")
    if (root / top).exists():
        # Only an incomplete layout reaches here (fetch checked); it would block the move.
        logger.warning("%s: removing the incomplete %s left in the cache", ds.name, root / top)
        shutil.rmtree(root / top)
    os.replace(out / top, root / top)


def fetch(
    name: str,
    *,
    downloader: Callable[[str, Path], None] = _download,
    generator: Callable[[LdbcDataset, Path], None] = _generate,
) -> Path:
    """Return the verified ``composite-projected-fk`` directory of data set *name*.

    Downloads and extracts, or generates, on first use. A generated data set is
    written to a temporary directory and moved into the cache only once Datagen
    has finished, so an interrupted run leaves nothing behind. A cached copy is
    re-verified on every call (a few seconds at SF0.1), so a corrupted or
    hand-edited cache is caught rather than loaded.
    """
    ds = DATASETS.get(name)
    if ds is None:
        raise LdbcDatasetError(f"unknown LDBC data set {name!r}; known: {', '.join(sorted(DATASETS))}")

    root = cache_dir() / ds.name
    layout = root / ds.layout_dir_name
    if not layout.is_dir():
        root.mkdir(parents=True, exist_ok=True)
        # ignore_cleanup_errors: a failed Datagen run on Linux can leave root-owned files.
        with tempfile.TemporaryDirectory(dir=root, ignore_cleanup_errors=True) as tmp:
            if ds.url is None:
                _generate_into(ds, Path(tmp), root, generator)
            else:
                _download_into(ds, ds.url, Path(tmp), root, downloader)
        if not layout.is_dir():
            source = "Datagen output" if ds.generated else "archive"
            raise LdbcDatasetError(f"{ds.name}: {source} did not contain {ds.layout_dir_name}")

    actual = content_digest(layout / "initial_snapshot")
    if actual != ds.content_digest:
        raise LdbcDatasetError(
            f"{ds.name}: content digest mismatch in {layout} (expected {ds.content_digest}, got {actual}). "
            "LDBC changed the rows, or the cache is corrupt. Delete the cache directory to re-download; "
            "if the mismatch persists, the oracle snapshots must be re-recorded before the pin is updated."
        )
    return layout
