"""Fetch, verify and cache LDBC SNB data sets (docs/ldbc_benchmark_plan.md D6).

Nothing generated by LDBC is committed. A data set is downloaded on first use
into ``$LDBC_CACHE_DIR`` (default ``~/.cache/arango-cypher/ldbc``), extracted,
and verified against a pinned **content digest** before anything reads it.

Why a content digest and not the archive's SHA-256: LDBC rebuilds the sample
archives (the SF0.003 zips fetched on 2026-10-23 were packed 2026-10-18), and
Spark names each part file with a fresh UUID, so the archive bytes change on
every republish while the rows do not. The digest covers each entity's
decompressed rows, sorted, keyed by entity path — independent of part-file
names, partitioning and zip metadata. If the *rows* change, the digest fails
and every recorded oracle snapshot is suspect, which is exactly when the run
must stop.
"""

from __future__ import annotations

import gzip
import hashlib
import logging
import os
import shutil
import tempfile
import urllib.request
import zipfile
from collections.abc import Callable, Iterator
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

logger = logging.getLogger(__name__)

Encoding = Literal["epoch_ms", "iso"]

#: Seconds a single download may take before it is abandoned.
DOWNLOAD_TIMEOUT_S = 120

_LAYOUT_SUBDIR = Path("graphs") / "csv" / "bi" / "composite-projected-fk"


class LdbcDatasetError(RuntimeError):
    """A data set could not be fetched, unpacked or verified."""


@dataclass(frozen=True)
class LdbcDataset:
    name: str
    scale_factor: str
    #: How ``datetime``/``date`` columns are written: epoch milliseconds (the
    #: Interactive v2 reference) or ISO-8601 text (the BI reference).
    encoding: Encoding
    url: str
    #: Top-level directory inside the archive.
    archive_root: str
    #: :func:`content_digest` of ``initial_snapshot/``.
    content_digest: str
    #: ``ldbc_snb_datagen_spark`` commit named in the archive's README.
    datagen_commit: str

    @property
    def layout_dir_name(self) -> Path:
        return Path(self.archive_root) / _LAYOUT_SUBDIR


_SAMPLE_BASE = "https://ldbcouncil.org/ldbc_snb_datagen_spark"
_DATAGEN_COMMIT = "a2210c52ddeceeeafbbdd4d4d166d0d0da82f739"

DATASETS: dict[str, LdbcDataset] = {
    d.name: d
    for d in (
        LdbcDataset(
            name="sf0.003-epoch-ms",
            scale_factor="0.003",
            encoding="epoch_ms",
            url=f"{_SAMPLE_BASE}/social-network-sf0.003-bi-composite-projected-fk-neo4j-compressed-epoch-millis.zip",
            archive_root="social-network-sf0.003-bi-composite-projected-fk-neo4j-compressed-epoch-millis",
            content_digest="90061e0cd2d1dc5b569747bc543dc15ce4c4c667e69671ab5226937c46674168",
            datagen_commit=_DATAGEN_COMMIT,
        ),
        LdbcDataset(
            name="sf0.003-iso",
            scale_factor="0.003",
            encoding="iso",
            url=f"{_SAMPLE_BASE}/social-network-sf0.003-bi-composite-projected-fk-neo4j-compressed.zip",
            archive_root="social-network-sf0.003-bi-composite-projected-fk-neo4j-compressed",
            content_digest="67f730cae61e621b735469c19cb804e7ff35f3781e1ec467df892da39edfbe07",
            datagen_commit=_DATAGEN_COMMIT,
        ),
    )
}


def cache_dir() -> Path:
    raw = os.environ.get("LDBC_CACHE_DIR", "").strip()
    return Path(raw).expanduser() if raw else Path.home() / ".cache" / "arango-cypher" / "ldbc"


def entity_dirs(root: Path) -> Iterator[Path]:
    """Every ``<part>/<Entity>`` directory under *root*, in sorted order."""
    for part in sorted(p for p in root.iterdir() if p.is_dir()):
        yield from sorted(p for p in part.iterdir() if p.is_dir())


def part_files(entity_dir: Path) -> list[Path]:
    """The CSV part files of one entity, sorted; Spark markers are skipped."""
    files = sorted(
        p for p in entity_dir.iterdir() if p.name.startswith("part-") and p.suffix in {".gz", ".csv"}
    )
    return files


def _read_lines(path: Path) -> list[bytes]:
    opener = gzip.open if path.suffix == ".gz" else open
    with opener(path, "rb") as fh:  # type: ignore[operator]
        return fh.read().splitlines()


def content_digest(snapshot_dir: Path) -> str:
    """SHA-256 over each entity's path and its sorted decompressed rows."""
    if not snapshot_dir.is_dir():
        raise LdbcDatasetError(f"cannot digest {snapshot_dir}: not a directory")
    h = hashlib.sha256()
    for ent in entity_dirs(snapshot_dir):
        h.update(f"{ent.parent.name}/{ent.name}\n".encode())
        rows: list[bytes] = []
        for f in part_files(ent):
            rows.extend(_read_lines(f))
        for row in sorted(rows):
            h.update(row + b"\n")
    return h.hexdigest()


#: ldbcouncil.org answers 403 to urllib's default ``Python-urllib/x.y`` agent.
_USER_AGENT = "arango-cypher-ldbc-harness/1.0 (+https://github.com/arango-solutions-org/arango-cypher)"


def _download(url: str, dest: Path) -> None:
    req = urllib.request.Request(url, headers={"User-Agent": _USER_AGENT})
    with urllib.request.urlopen(req, timeout=DOWNLOAD_TIMEOUT_S) as resp, dest.open("wb") as out:  # noqa: S310 — https URL from the pinned catalog
        shutil.copyfileobj(resp, out)


def _safe_extract(archive: Path, target: Path) -> None:
    """Extract *archive* into *target*, refusing members that escape it."""
    target_resolved = target.resolve()
    with zipfile.ZipFile(archive) as zf:
        for member in zf.infolist():
            dest = (target / member.filename).resolve()
            if dest != target_resolved and target_resolved not in dest.parents:
                raise LdbcDatasetError(
                    f"{archive.name}: member {member.filename!r} would extract outside {target}"
                )
        zf.extractall(target)


def fetch(
    name: str,
    *,
    downloader: Callable[[str, Path], None] = _download,
) -> Path:
    """Return the verified ``composite-projected-fk`` directory of data set *name*.

    Downloads and extracts on first use. A cached copy is re-verified on every
    call (digesting SF0.003 takes well under a second), so a corrupted or
    hand-edited cache is caught rather than loaded.
    """
    ds = DATASETS.get(name)
    if ds is None:
        raise LdbcDatasetError(f"unknown LDBC data set {name!r}; known: {', '.join(sorted(DATASETS))}")

    root = cache_dir() / ds.name
    layout = root / ds.layout_dir_name
    if not layout.is_dir():
        root.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(dir=root) as tmp:
            archive = Path(tmp) / "archive.zip"
            logger.info("downloading LDBC data set %s from %s", ds.name, ds.url)
            try:
                downloader(ds.url, archive)
            except OSError as e:
                raise LdbcDatasetError(f"download of {ds.name} from {ds.url} failed: {e}") from e
            try:
                _safe_extract(archive, root)
            except zipfile.BadZipFile as e:
                raise LdbcDatasetError(f"{ds.name}: downloaded archive is not a zip file: {e}") from e
        if not layout.is_dir():
            raise LdbcDatasetError(f"{ds.name}: archive did not contain {ds.layout_dir_name}")

    actual = content_digest(layout / "initial_snapshot")
    if actual != ds.content_digest:
        raise LdbcDatasetError(
            f"{ds.name}: content digest mismatch in {layout} (expected {ds.content_digest}, got {actual}). "
            "LDBC changed the rows, or the cache is corrupt. Delete the cache directory to re-download; "
            "if the mismatch persists, the oracle snapshots must be re-recorded before the pin is updated."
        )
    return layout
